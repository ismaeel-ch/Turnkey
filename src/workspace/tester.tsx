/* ===== Turnkey prototype · the Tester: test cases written by an agent, run by code, failures sent back for repair =====
   The other tests are generated by code from the definitions. These are different: the Tester agent reads the brief
   (its rules and user stories) and writes test cases as data, in the same step vocabulary as the guided tour. Code plays
   every case against the real endpoints inside a savepoint. When one fails, the orchestrator sends it back to the agent
   that owns the failing part, applies that agent's repair as a checked change, and runs everything again.
   The app is "ready" only after this, and a version can be released only when every test passes. */
AGENTS.tester = {
  name: 'Tester',
  icon: 'beaker',
  acc: 'seafoam',
  role: 'Writes test cases from the brief and sends failures back for repair',
};
export const CASE_DO = ['create', 'see', 'hidden', 'transition', 'denied', 'invalid', 'open'],
  QA_ROUNDS = 3; // one run, then at most two repair rounds
export const CASE_EXPECT = {
  create: '201 Created',
  see: 'the record is in the list',
  hidden: 'the record is not in the list',
  transition: '200 OK',
  denied: 'refused with 403',
  invalid: 'refused with 400',
  open: 'the page opens',
};
export function normCases(o, def) {
  const roleIds = def.brief.roles.map((r) => r.id),
    seen = {};
  return arr(o && o.cases)
    .map((c, i) => {
      c = c || {};
      const steps = arr(c.steps)
        .map((x) => {
          x = x || {};
          return {
            role: snake(x.role),
            user: str(x.user).toLowerCase() || null,
            do: CASE_DO.includes(x.do) ? x.do : 'open',
            screen: str(x.screen),
            table: snake(x.table),
            values: x.values && typeof x.values === 'object' && !Array.isArray(x.values) ? x.values : {},
            transition: snake(x.transition),
            action: snake(x.action),
            say: str(x.say).slice(0, 200),
          };
        })
        .filter((x) => roleIds.includes(x.role) && (!x.table || tableOf(def, x.table)))
        .slice(0, 6);
      let id = snake(c.id || c.name).slice(0, 48) || 'case_' + (i + 1);
      while (seen[id]) id += '_2';
      seen[id] = 1;
      return {
        id,
        name: str(c.name).slice(0, 140) || 'Case ' + (i + 1),
        why: str(c.why).slice(0, 220),
        steps,
      };
    })
    .filter((c) => c.steps.length)
    .slice(0, 10);
}
export function suggestCases(app) {
  // what code writes when there is no model and no saved answer: one case for every kind of rule the app has
  const def = app.def,
    P = def.process,
    roles = def.brief.roles,
    users = def.users,
    out = [],
    rules = arr(def.brief.rules),
    VERB = {
      create: 'add',
      update: 'change',
      delete: 'delete',
      list: 'see',
    };
  const ruleFor = (words) => rules.find((r) => words.every((w) => r.toLowerCase().includes(String(w).toLowerCase()))) || '',
    lc = (s) => String(s).toLowerCase();
  const refused = [];
  roles.forEach((r) =>
    def.tables.forEach((t) => {
      const a = accOf(def, r.id, t.name);
      if (a.list === 'none') {
        refused.push({
          r,
          t,
          act: 'list',
          w: 1,
        });
        return;
      }
      if (!a.delete)
        refused.push({
          r,
          t,
          act: 'delete',
          w: ruleFor([r.name]) ? 4 : 2,
        });
      if (!a.create)
        refused.push({
          r,
          t,
          act: 'create',
          w: ruleFor([r.name]) ? 5 : 3,
        });
      if (a.update === 'none' && a.create)
        refused.push({
          r,
          t,
          act: 'update',
          w: 2,
        });
    }),
  );
  const pick = [],
    perRole = {};
  refused
    .sort((a, b) => b.w - a.w)
    .forEach((x) => {
      if (pick.length < 4 && (perRole[x.r.id] || 0) < 2 && !pick.some((p) => p.r === x.r && p.t === x.t)) {
        pick.push(x);
        perRole[x.r.id] = (perRole[x.r.id] || 0) + 1;
      }
    });
  pick.forEach((x) =>
    out.push({
      name: x.r.name + ' cannot ' + VERB[x.act] + ' ' + lc(x.t.label),
      why:
        ruleFor([x.r.name]) ||
        ruleFor([x.t.one]) ||
        'From the access rules: this role has no right to ' + VERB[x.act] + ' ' + lc(x.t.label) + '.',
      steps: [
        {
          role: x.r.id,
          do: 'denied',
          table: x.t.name,
          action: x.act,
          say: x.r.name + ' tries to ' + VERB[x.act] + ' ' + lc(x.act === 'create' ? x.t.one : x.t.label) + ' and is refused.',
        },
      ],
    }),
  );
  if (P) {
    const t = tableOf(def, P.table),
      maker = roles.find((r) => accOf(def, r.id, t.name).create);
    if (maker && t.columns.some((c) => c.required && c.name !== P.column && c.name !== t.owner))
      out.push({
        name: (/^[aeiou]/i.test(t.one) ? 'An ' : 'A ') + lc(t.one) + ' without its required details is refused',
        why: 'Required fields are part of the table the Database agent wrote, so the endpoint must enforce them.',
        steps: [
          {
            role: maker.id,
            do: 'invalid',
            table: t.name,
            values: {},
            say: maker.name + ' tries to save an empty ' + lc(t.one) + '.',
          },
        ],
      });
    P.transitions
      .filter((x) => x.roles.length < roles.length)
      .slice(0, 2)
      .forEach((tr) => {
        const no = roles.find((r) => !tr.roles.includes(r.id));
        if (no)
          out.push({
            name: no.name + ' cannot ' + lc(tr.label),
            why:
              ruleFor([no.name]) ||
              ruleFor([tr.label.split(' ')[0]]) ||
              'The workflow lets only ' + tr.roles.map((id) => roleName(def, id)).join(' or ') + ' take this step.',
            steps: [
              {
                role: no.id,
                do: 'denied',
                table: t.name,
                action: tr.id,
                say: no.name + ' tries to ' + lc(tr.label) + ' and is refused.',
              },
            ],
          });
      });
  }
  const own = roles.find(
      (r) =>
        def.tables.some((t) => accOf(def, r.id, t.name).list === 'own' && accOf(def, r.id, t.name).create) &&
        users.filter((u) => u.role === r.id).length > 1,
    ),
    mk =
      own && def.tour.find((s) => s.do === 'create' && s.role === own.id && accOf(def, own.id, s.table || (P && P.table)).list === 'own');
  if (own && mk) {
    const us = appUsers(app).filter((u) => u.role === own.id),
      t = tableOf(def, mk.table || P.table);
    out.push({
      name: 'One ' + lc(own.name) + " does not see another's " + lc(t.label),
      why: ruleFor(['own']) || 'The access rules give this role its own ' + lc(t.label) + ' only.',
      steps: [
        Object.assign({}, mk, {
          user: us[0].username,
          say: us[0].name + ' adds ' + lc(t.one) + '.',
        }),
        {
          role: own.id,
          user: us[1].username,
          do: 'hidden',
          table: t.name,
          say: us[1].name + ' looks for it and does not find it.',
        },
      ],
    });
  }
  return out;
}
