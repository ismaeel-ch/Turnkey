export function normCases(o: Untrusted, def: BriefedDef): TestCase[] {
  const roleIds = def.brief.roles.map((r) => r.id),
    seen: Dict<number> = {};
  return arr(o && o.cases)
    .map((c: Untrusted, i) => {
      c = c || {};
      const steps: TourStep[] = arr(c.steps)
        .map((x: Untrusted) => {
          x = x || {};
          return {
            role: snake(x.role),
            user: str(x.user).toLowerCase() || null,
            do: CASE_DO.includes(x.do) ? x.do : 'open',
            screen: str(x.screen),
            table: snake(x.table),
            values: x.values && typeof x.values === 'object' && !Array.isArray(x.values) ? x.values : {},
            transition: snake(x.transition),
            action: snake(x.action),
            say: str(x.say).slice(0, 200),
          };
        })
        .filter((x) => roleIds.includes(x.role) && (!x.table || tableOf(def, x.table)))
        .slice(0, 6);
      let id = snake(c.id || c.name).slice(0, 48) || 'case_' + (i + 1);
      while (seen[id]) id += '_2';
      seen[id] = 1;
      return {
        id,
        name: str(c.name).slice(0, 140) || 'Case ' + (i + 1),
        why: str(c.why).slice(0, 220),
        steps,
      };
    })
    .filter((c) => c.steps.length)
    .slice(0, 10);
}
/**
 * A model often writes a case that jumps over a workflow step: it creates a record, then runs a transition that only
 * starts from a later state (409 "Cannot send for approval while it is received"). No repair can fix that test, so
 * before the cases run, code walks each case through the workflow and adds the missing steps along the shortest path,
 * each run by a role that may take that step and see the record. A case whose state cannot be followed is left as is.
 */
export function fillWorkflowSteps(cases: TestCase[], def: BackedDef): TestCase[] {
  const P = def.process;
  if (!P || !P.transitions.length) return cases;
  const byId = (id: string) => P.transitions.find((x) => x.id === id),
    path = (from: string, goal: string[]) => {
      // breadth-first over the transitions; returns the transitions that reach one of the goal states
      const back: Dict<{ prev: string; tr: (typeof P.transitions)[number] } | null> = { [from]: null },
        queue = [from];
      while (queue.length) {
        const at = queue.shift() as string;
        if (goal.includes(at)) {
          const out: (typeof P.transitions)[number][] = [];
          for (let k = at; back[k]; k = (back[k] as { prev: string }).prev)
            out.unshift((back[k] as { tr: (typeof P.transitions)[number] }).tr);
          return out;
        }
        P.transitions
          .filter((x) => x.from.includes(at) && !(x.to in back))
          .forEach((x) => {
            back[x.to] = { prev: at, tr: x };
            queue.push(x.to);
          });
      }
      return null;
    },
    runner = (tr: (typeof P.transitions)[number], prefer: string) => {
      const sees = (r: string) => accOf(def, r, P.table).list !== 'none';
      return tr.roles.includes(prefer) && sees(prefer)
        ? prefer
        : tr.roles.find((r) => accOf(def, r, P.table).list === 'all') || tr.roles.find(sees);
    };
  return cases.map((c) => {
    let state: string | null = null,
      added = 0;
    const steps: TourStep[] = [];
    for (const s of c.steps) {
      const onProcess = (s.table || P.table) === P.table;
      if (s.do === 'create' && onProcess) state = P.initial;
      else if (s.do === 'transition' && onProcess && state) {
        const tr = byId(s.transition || '');
        if (!tr) state = null;
        else {
          if (!tr.from.includes(state)) {
            const hops = path(state, tr.from),
              who = hops && hops.map((h) => runner(h, s.role));
            if (hops && who && who.every(Boolean) && steps.length + hops.length < 9) {
              hops.forEach((h, k) =>
                steps.push({
                  role: who[k] as string,
                  user: who[k] === s.role ? s.user || null : null,
                  do: 'transition',
                  table: P.table,
                  values: {},
                  transition: h.id,
                  say: roleName(def, who[k] as string) + ' moves it on first: ' + h.label.toLowerCase() + '.',
                }),
              );
              added += hops.length;
            }
          }
          state = tr.to;
        }
      }
      steps.push(s);
    }
    return added ? { ...c, steps } : c;
  });
}
/** A case as code writes it, before normCases gives it an id. */
type CaseDraft = Omit<TestCase, 'id'>;
export function suggestCases(app: BackedApp): CaseDraft[] {
  // what code writes when there is no model and no saved answer: one case for every kind of rule the app has
  const def = app.def,
    P = def.process,
    roles = def.brief.roles,
    users = def.users,
    out: CaseDraft[] = [],
    rules = arr<string>(def.brief.rules),
    VERB: Record<Act, string> = {
      create: 'add',
      update: 'change',
      delete: 'delete',
      list: 'see',
    };
  const ruleFor = (words: string[]) => rules.find((r) => words.every((w) => r.toLowerCase().includes(String(w).toLowerCase()))) || '',
    lc = (s: unknown) => String(s).toLowerCase();
  const refused: Refusal[] = [];
  roles.forEach((r) =>
    def.tables.forEach((t) => {
      const a = accOf(def, r.id, t.name);
      if (a.list === 'none') {
        refused.push({
          r,
          t,
          act: 'list',
          w: 1,
        });
        return;
      }
      if (!a.delete)
        refused.push({
          r,
          t,
          act: 'delete',
          w: ruleFor([r.name]) ? 4 : 2,
        });
      if (!a.create)
        refused.push({
          r,
          t,
          act: 'create',
          w: ruleFor([r.name]) ? 5 : 3,
        });
      if (a.update === 'none' && a.create)
        refused.push({
          r,
          t,
          act: 'update',
          w: 2,
        });
    }),
  );
  const pick: Refusal[] = [],
    perRole: Dict<number> = {};
  refused
    .sort((a, b) => b.w - a.w)
    .forEach((x) => {
      if (pick.length < 4 && (perRole[x.r.id] || 0) < 2 && !pick.some((p) => p.r === x.r && p.t === x.t)) {
        pick.push(x);
        perRole[x.r.id] = (perRole[x.r.id] || 0) + 1;
      }
    });
  pick.forEach((x) =>
    out.push({
      name: x.r.name + ' cannot ' + VERB[x.act] + ' ' + lc(x.t.label),
      why:
        ruleFor([x.r.name]) ||
        ruleFor([x.t.one]) ||
        'From the access rules: this role has no right to ' + VERB[x.act] + ' ' + lc(x.t.label) + '.',
      steps: [
        {
          role: x.r.id,
          do: 'denied',
          table: x.t.name,
          action: x.act,
          say: x.r.name + ' tries to ' + VERB[x.act] + ' ' + lc(x.act === 'create' ? x.t.one : x.t.label) + ' and is refused.',
        },
      ],
    }),
  );
  const main = mainTable(def);
  if (P && main) {
    const t = main,
      maker = roles.find((r) => accOf(def, r.id, t.name).create);
    if (maker && t.columns.some((c) => c.required && c.name !== P.column && c.name !== t.owner))
      out.push({
        name: (/^[aeiou]/i.test(t.one) ? 'An ' : 'A ') + lc(t.one) + ' without its required details is refused',
        why: 'Required fields are part of the list the List builder wrote, so the endpoint must enforce them.',
        steps: [
          {
            role: maker.id,
            do: 'invalid',
            table: t.name,
            values: {},
            say: maker.name + ' tries to save an empty ' + lc(t.one) + '.',
          },
        ],
      });
    P.transitions
      .filter((x) => x.roles.length < roles.length)
      .slice(0, 2)
      .forEach((tr) => {
        const no = roles.find((r) => !tr.roles.includes(r.id));
        if (no)
          out.push({
            name: no.name + ' cannot ' + lc(tr.label),
            why:
              ruleFor([no.name]) ||
              ruleFor([tr.label.split(' ')[0]]) ||
              'The workflow lets only ' + tr.roles.map((id) => roleName(def, id)).join(' or ') + ' take this step.',
            steps: [
              {
                role: no.id,
                do: 'denied',
                table: t.name,
                action: tr.id,
                say: no.name + ' tries to ' + lc(tr.label) + ' and is refused.',
              },
            ],
          });
      });
  }
  const own = roles.find(
      (r) =>
        def.tables.some((t) => accOf(def, r.id, t.name).list === 'own' && accOf(def, r.id, t.name).create) &&
        users.filter((u) => u.role === r.id).length > 1,
    ),
    mk =
      own &&
      def.tour.find((s) => s.do === 'create' && s.role === own.id && accOf(def, own.id, s.table || (main ? main.name : '')).list === 'own');
  if (own && mk) {
    const us = appUsers(app).filter((u) => u.role === own.id),
      t = tableOf(def, mk.table || main?.name) as AppTable;
    out.push({
      name: 'One ' + lc(own.name) + " does not see another's " + lc(t.label),
      why: ruleFor(['own']) || 'The access rules give this role its own ' + lc(t.label) + ' only.',
      steps: [
        Object.assign({}, mk, {
          user: us[0].username,
          say: us[0].name + ' adds ' + lc(t.one) + '.',
        }),
        {
          role: own.id,
          user: us[1].username,
          do: 'hidden',
          table: t.name,
          say: us[1].name + ' looks for it and does not find it.',
        },
      ],
    });
  }
  return out;
}
