/* ===== Turnkey prototype · the Tester: test cases written by an agent, run by code, failures sent back for repair =====
   The other tests are generated by code from the definitions. These are different: the Tester agent reads the brief
   (its rules and user stories) and writes test cases as data, in the same step vocabulary as the guided tour. Code plays
   every case against the real endpoints inside a savepoint. When one fails, the orchestrator sends it back to the agent
   that owns the failing part, applies that agent's repair as a checked change, and runs everything again.
   The app is "ready" only after this, and a version can be released only when every test passes. */
