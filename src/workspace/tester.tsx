  '\n\nWORKFLOW:\n' +
  pFlow(app.def) +
  '\n\nFAILING TESTS:\n' +
  fails
    .slice(0, 8)
    .map((f) => '- [' + f.suiteName + '] ' + f.name + ' → ' + f.actual)
    .join('\n') +
  '\n\nTEST CASES (written by the Tester from the brief):\n' +
  JSON.stringify(
    arr(app.def.cases)
      .filter((c) => fails.some((f) => f.id === 'case:' + c.id))
      .map((c) => ({
        id: c.id,
        name: c.name,
        why: c.why,
        steps: c.steps.map((s) => ({
          role: s.role,
          do: s.do,
          table: s.table,
          action: s.action,
          transition: s.transition,
        })),
      })),
  ) +
  '\n\nReply with changes in plain words, one per fix, from this list of forms only: "Stop the <role name> from creating|editing|deleting|seeing <table label>", "Let the <role name> create|edit|delete|see <table label>", "Add a <field name> field to <table label>", "Remove the <field name> field from <table label>". If a test case itself contradicts the brief, list its id under "wrong" instead of changing the app.\n\nFORMAT: {"say":"one sentence","fixes":[{"change":"","for":"name of the failing test"}],"wrong":[{"case":"case id","why":""}]}';
export function keepFix(app, text, ctx) {
  // one plain change request, applied for real. applyChangeSync works inside a savepoint and puts everything back if any check fails.
  let plan;
  try {
    plan = parseChange(app, text);
  } catch (e) {
    plan = {};
  }
  if (!plan.ops || !plan.ops.length)
    return {
      ok: false,
      why: 'It could not be read as a change.',
    };
  const p = planOps(app, plan.ops);
  if (!p.steps.length)
    return {
      ok: false,
      why: p.errors[0] || 'It cannot be applied to this app.',
    };
  if (p.steps.some((s) => s.destructive))
    return {
      ok: false,
      why: 'It deletes data, so it waits for your approval in chat.',
    };
  let res;
  try {
    res = applyChangeSync(app, p.steps, ctx);
  } catch (e) {
    return {
      ok: false,
      why: String((e && e.message) || e),
    };
  }
  if (res.failed)
    return {
      ok: false,
      why: stName(res.failed) + ' would fail: ' + (((res.per[res.failed] || {}).issues || [])[0] || 'a check'),
    };
  STATIONS.forEach((st, i) => {
    const r = res.per[st.id],
      L = app.line[st.id];
    if (i >= res.first && r) {
      L.checks = r.checks;
      L.facts = r.facts;
    }
  });
  p.steps.forEach((s) => logChange(app, s.text, s.station));
  app.updated = Date.now();
  return {
    ok: true,
    items: p.steps.map((s) => s.text),
    station: STATIONS[res.first].id,
  };
}
/**
 * The Tester's part of a build, as the four steps the workflow graph calls: write the cases, run every test, send the
 * failures back for repair, and record the result. The graph decides how often `run` and `repair` happen (at most
 * QA_ROUNDS runs) and emits the `tests` step events itself.
 */
export function testerSteps(app, run) {
  const live = app.mode === 'live' && liveModelOn(),
    ctx = ctxOf(app, run, 'tester'),
    rec = REC[app.tpl];
  let Q = null,
    fails = [];
  async function write() {
    Q = app.qa = {
      status: 'working',
      by: '',
      rounds: [],
      t0: Date.now(),
      t1: null,
      dropped: [],
    };
    if (U.follow[app.id] !== false) U.sel[app.id] = 'qa';
    commit();
    const s1 = stepStart(run, 'tests', 'tester', 'Write test cases', live ? 'model' : 'tool');
    let raw = null;
    say(
      app,
      'tester',
      live
        ? 'Reading the brief and writing test cases for its rules and user stories.'
        : rec && rec.tester
          ? 'Writing test cases from the brief: one for every rule, and one refusal for every role that has limits.'
          : 'Writing test cases from the rules of the brief and the access rules.',
    );
    if (live) {
      try {
        raw = await callModel(app, run, 'tester', testerPrompt(app), 1);
        Q.by = 'model';
      } catch (e) {
        if (e instanceof Stopped || e.fatal) throw e;
        raw = null;
      }
    } else {
      await pace(app, 900);
      if (rec && rec.tester) {
        raw = rec.tester();
        Q.by = 'saved';
        run.replayed++;
      }
    }
    let cases = normCases(raw, app.def);
    if (cases.length < 2) {
      cases = normCases(
        {
          cases: suggestCases(app),
        },
        app.def,
      );
      Q.by = Q.by === 'model' ? "rules, because the model's cases could not be used" : 'rules';
    }
    app.def.cases = cases;
    app.rev++;
    stepEnd(s1, true);
    toolCall(
      ctx,
      'write_test_cases',
      {
        cases: cases.length,
      },
      () => ({
        written: cases.map((c) => c.name),
      }),
      'backend',
    );
    emit('STATE_DELTA', {
      app: app.id,
      delta: [
        {
          op: 'add',
          path: '/cases',
          value: cases.length + ' test cases',
        },
      ],
    });
    commit();
  }
  async function runRound({ round: n }) {
    Q.status = 'checking';
    commit();
    const s2 = stepStart(run, 'tests', 'orchestrator', n === 1 ? 'Run every test' : 'Run every test again', 'check');
    await pace(app, 800);
    const ts = runTestsSync(app);
    fails = failingTests(app);
    const R = {
      n,
      total: ts ? ts.total : 0,
      failed: ts ? ts.failed : 0,
      fails: fails.slice(0, 8).map((f) => ({
        name: f.name,
        suite: f.suiteName,
        actual: f.actual,
      })),
      fixes: [],
    };
    Q.rounds.push(R);
    stepEnd(s2, !R.failed);
    commit();
    return { total: R.total, failed: R.failed };
  }
  async function repair({ round: n }) {
    const R = Q.rounds[Q.rounds.length - 1];
    Q.status = 'sentback';
    run.retries++;
    say(
      app,
      'tester',
      R.failed +
        ' of ' +
        R.total +
        ' tests ' +
        (R.failed === 1 ? 'fails' : 'fail') +
        ': ' +
        fails
          .slice(0, 2)
          .map((f) => '“' + f.name + '” (' + f.actual + ')')
          .join('; ') +
        '. I am sending ' +
        (R.failed === 1 ? 'it' : 'them') +
        ' back for repair.',
      {
        type: 'error',
        issues: fails.slice(0, 3).map((f) => f.name + ': ' + f.actual),
      },
    );
    const s3 = stepStart(run, 'tests', 'backend', 'Repair', live ? 'model' : 'tool');
    let fixes = [],
      wrong = [];
    if (live) {
      try {
        const o = await callModel(app, run, 'backend', repairPrompt(app, fails), n);
        fixes = arr(o.fixes)
          .map((x) => ({
            by: 'backend',
            for: str(x && x.for),
            text: str(x && x.change),
          }))
          .filter((x) => x.text)
          .slice(0, 5);
        wrong = arr(o.wrong)
          .map((x) => ({
            id: snake(x && x.case),
            why: str(x && x.why),
          }))
          .filter((x) => app.def.cases.some((c) => c.id === x.id));
      } catch (e) {
        if (e instanceof Stopped || e.fatal) throw e;
      }
    }
    if (!fixes.length && !wrong.length) {
      await pace(app, 700);
      fixes = ruleRepairs(app, fails);
    }
    if (wrong.length) {
      app.def.cases = app.def.cases.filter((c) => !wrong.some((w) => w.id === c.id));
      app.rev++;
      wrong.forEach((w) => Q.dropped.push(w));
    }
    fixes.forEach((f) => {
      const r = keepFix(app, f.text, ctxOf(app, run, f.by));
      R.fixes.push({
        by: f.by,
        text: f.text,
        for: f.for,
        ok: r.ok,
        why: r.ok ? r.items.join('; ') : r.why,
        station: r.station || 'backend',
      });
    });
    stepEnd(s3, R.fixes.some((f) => f.ok) || wrong.length > 0);
    const okN = R.fixes.filter((f) => f.ok).length;
    if (!okN && !wrong.length) {
      say(
        app,
        'backend',
        'I could not find a repair that passes every check, so the failing ' +
          (R.failed === 1 ? 'test stays' : 'tests stay') +
          ' for you to decide.',
      );
      return { progress: false };
    }
    say(
      app,
      'backend',
      (okN
        ? 'Repaired: ' +
          R.fixes
            .filter((f) => f.ok)
            .map((f) => f.why)
            .join('; ') +
          '. '
        : '') +
        (wrong.length
          ? wrong.length +
            ' test case' +
            (wrong.length === 1 ? ' was' : 's were') +
            ' withdrawn because ' +
            (wrong.length === 1 ? 'it' : 'they') +
            ' did not match the brief. '
          : '') +
        'Each repair went through the same checks as a change you ask for.',
      {
        type: 'changed',
        items: R.fixes.filter((f) => f.ok).map((f) => f.why),
        reran: ['Tests'],
        skipped: [],
      },
    );
    commit();
    await pace(app, 500);
    return { progress: true };
  }
  async function done() {
    const last = Q.rounds[Q.rounds.length - 1];
    Q.status = last.failed ? 'failed' : 'ok';
    Q.t1 = Date.now();
    const repaired = Q.rounds.reduce((k, r) => k + r.fixes.filter((f) => f.ok).length, 0);
    say(
      app,
      'tester',
      last.failed
        ? last.failed +
            ' of ' +
            last.total +
            ' tests still fail. The app works, but a version can only be released when every test passes. Ask for a change in chat, or open the tests.'
        : 'All ' +
            last.total +
            ' tests pass' +
            (repaired ? ' after ' + repaired + (repaired === 1 ? ' repair' : ' repairs') : '') +
            ': ' +
            app.def.cases.length +
            ' cases I wrote and ' +
            (last.total - app.def.cases.length) +
            ' generated from the definitions.',
      {
        type: 'tests',
        total: last.total,
        passed: last.total - last.failed,
        failed: last.failed,
        suites: suiteOf(app).map((s) => ({
          name: s.name,
          n: s.tests.length,
        })),
      },
    );
    commit();
  }
  return { write, run: runRound, repair, done };
}

/* ---------- the Tester in the inspector ---------- */
export function TesterPanel({ app }) {
  const Q = app.qa,
    cases = arr(app.def.cases),
    R = TESTS[app.id],
    res = R && R.rev === app.rev ? R.res : {},
    st = testStats(app),
    busy = !!RUNS[app.id];
  if (!Q && !cases.length)
    return (
      <section className="inspector review-insp">
        <div className="insp-head">
          <AgentAv id="tester" />
          <div className="col gap0 grow">
            <strong>Tester</strong>
            <span className="t-cap muted">{AGENTS.tester.role}</span>
          </div>
        </div>
        <div className="insp-body">
          <Empty
            icon="beaker"
            title="No test cases yet"
            text="The Tester writes them when the six stations have passed, then every test runs before the app is called ready."
          />
        </div>
      </section>
    );
  const tone = Q ? (Q.status === 'ok' ? 'success' : Q.status === 'failed' ? 'danger' : 'info') : 'neutral';
  return (
    <section className="inspector review-insp" aria-label="Tester">
      <div className="insp-head">
        <AgentAv id="tester" />
        <div className="col gap0 grow">
          <strong>Tester</strong>
          <span className="t-cap muted">{AGENTS.tester.role}</span>
        </div>
        <span className={'badge b-' + tone}>
          {Q
            ? Q.status === 'ok'
              ? 'All tests pass'
              : Q.status === 'failed'
                ? 'Tests fail'
                : Q.status === 'sentback'
                  ? 'Sent back for repair'
                  : 'Working'
            : 'Not run in this session'}
        </span>
        <button className="btn sm" disabled={busy || !testable(app)} onClick={() => runTests(app)}>
          <Icon n="play" s="16" />
          Run every test
        </button>
      </div>
      <div className="insp-body col gap12">
        <p className="muted t-cap">
          {Q && Q.by === 'model'
            ? 'The model wrote these cases from the brief.'
            : Q && Q.by === 'saved'
              ? 'These cases are part of the saved build. In a Live build the model writes them from the brief.'
              : 'Written by rules in code from the brief and the access rules. In a Live build the model writes them.'}
          {' Code plays each one against the real endpoints inside a savepoint and rolls it back.'}
          {app.tpl && REC[app.tpl] && REC[app.tpl].slip ? ' ' + REC[app.tpl].slip : ''}
        </p>
        {Q && Q.rounds.length > 0 && (
          <ol className="qa-rounds">
            {Q.rounds.map((r) => (
              <li key={r.n} className={cx('qa-round', r.failed ? 'bad' : 'ok')}>
                <div className="row gap8">
                  <Icon n={r.failed ? 'warning' : 'checkCircle'} s="16" cls={r.failed ? 'bad' : 'ok'} />
                  <strong>
                    {'Run '}
                    {r.n}
                  </strong>
                  <span className="grow">{r.failed ? r.failed + ' of ' + r.total + ' failed' : 'all ' + r.total + ' passed'}</span>
                </div>
                {r.fails.length > 0 && (
                  <ul className="plain qa-fails">
                    {r.fails.slice(0, 4).map((f, i) => (
                      <li key={i}>
                        <span className="badge b-outline">{f.suite}</span> {f.name}{' '}
                        <span className="muted">
                          {'→ '}
                          {f.actual}
                        </span>
                      </li>
                    ))}
                  </ul>
                )}
                {r.fixes.map((f, i) => (
                  <div key={i} className={cx('qa-fix', f.ok ? 'ok' : 'bad')}>
                    <AgentAv id={f.by} size="xs" />
                    <span className="grow">
                      <strong>
                        {AGENTS[f.by].name} {f.ok ? 'repaired it' : 'tried a repair'}:
                      </strong>{' '}
                      {f.text}
                      {f.ok ? '' : ' · not applied: ' + f.why}
                    </span>
                  </div>
                ))}
              </li>
            ))}
          </ol>
        )}
        {Q && Q.dropped.length > 0 && (
          <MBar tone="info">
            {Q.dropped.length}
            {' case'}
            {Q.dropped.length === 1 ? ' was' : 's were'}
            {' withdrawn: '}
            {Q.dropped.map((d) => d.why).join('; ')}
          </MBar>
        )}
        <div className="col gap4">
          <div className="row between">
            <strong>
              {cases.length}
              {' test cases'}
            </strong>
            <span className="t-cap muted">{st ? st.total - cases.length + ' more are generated from the definitions' : ''}</span>
          </div>
          <ul className="plain qa-cases">
            {cases.map((c) => {
              const r = res['case:' + c.id];
              return (
                <li key={c.id} className={cx('qa-case', r && (r.ok ? 'ok' : 'bad'))}>
                  <div className="row gap8">
                    <Icon n={!r ? 'circle' : r.ok ? 'checkCircle' : 'errorCircle'} s="16" cls={!r ? 'muted' : r.ok ? 'ok' : 'bad'} />
                    <strong className="grow">{c.name}</strong>
                    <span className="t-cap muted">
                      {c.steps.length}
                      {' step'}
                      {c.steps.length === 1 ? '' : 's'}
                    </span>
                  </div>
                  {c.why && (
                    <span className="t-cap muted">
                      {'Protects: '}
                      {c.why}
                    </span>
                  )}
                  <ol className="qa-steps">
                    {c.steps.map((s, i) => (
                      <li key={i}>
                        <span>{s.say || roleName(app.def, s.role) + ' · ' + s.do + ' ' + s.table}</span>
                        <span className="badge b-outline">{CASE_EXPECT[s.do]}</span>
                      </li>
                    ))}
                  </ol>
                  {r && !r.ok && <span className="t-cap bad-t">{r.actual}</span>}
                </li>
              );
            })}
          </ul>
        </div>
      </div>
    </section>
  );
}
