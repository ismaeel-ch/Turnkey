/**
 * Cases no change to the app could make pass, taken out before they run: a transition the app does not have (a model
 * writes "mark_paid" for an app with no workflow), or an "incomplete" create that leaves out only the stage field,
 * which the workflow always fills in. Each is listed with the reason, like a case the Tester withdraws.
 */
export function unplayable(cases: TestCase[], def: BackedDef): { keep: TestCase[]; drop: { id: string; why: string }[] } {
  const P = def.process,
    trs = P ? P.transitions.map((t) => t.id) : [],
    drop: { id: string; why: string }[] = [];
  const why = (c: TestCase): string | null => {
    for (const s of c.steps) {
      if (s.do === 'transition' && !trs.includes(s.transition || ''))
        return trs.length
          ? 'It runs "' + (s.transition || '') + '", which is not a step of the workflow.'
          : 'It runs "' + (s.transition || '') + '", but this app has no workflow.';
      if (s.do === 'invalid') {
        const t = tableOf(def, s.table || (P && P.table) || ''),
          v = s.values || {},
          missing = t ? t.columns.filter((c) => c.required && (v[c.name] === undefined || v[c.name] === null || v[c.name] === '')) : [];
        if (t && missing.length && P && P.table === t.name && missing.every((c) => c.name === P.column))
          return 'It leaves out only ' + P.column + ', which the workflow fills in on every new record.';
      }
    }
    return null;
  };
  const keep = cases.filter((c) => {
    const w = why(c);
    if (w) drop.push({ id: c.id, why: w });
    return !w;
  });
  return { keep, drop };
}
export function failingTests(app: AppRecord): FailingTest[] {
  const R = TESTS[app.id],
    out: FailingTest[] = [];
  if (!R || R.rev !== app.rev) return out;
  suiteOf(app).forEach((s) =>
    s.tests.forEach((t) => {
      const r = R.res[t.id];
      if (r && !r.ok)
        out.push({
          id: t.id,
          name: t.name,
          suite: s.id,
          suiteName: s.name,
          station: s.station,
          actual: r.actual,
        });
    }),
  );
  return out;
}
export function ruleRepairs(app: BackedApp, fails: FailingTest[]): Repair[] {
  // without a model, the repair rules can read: an access rule that lets through what a case says must be refused, or refuses what must work
  const def = app.def,
    out: Repair[] = [],
    ING: Dict<string> = {
      create: 'creating',
      update: 'editing',
      delete: 'deleting',
      list: 'seeing',
    };
  fails
    .filter((f) => f.suite === 'scenarios')
    .forEach((f) => {
      const c = (def.cases || []).find((x) => 'case:' + x.id === f.id),
        m = /^step (\d+)/.exec(f.actual),
        s = c && m ? c.steps[+m[1] - 1] : null,
        t = s ? tableOf(def, s.table || (def.process && def.process.table)) : null;
      if (!c || !s || !t) return;
      const who = roleName(def, s.role).toLowerCase();
      if (s.do === 'denied' && ING[s.action || 'create'])
        out.push({
          by: 'backend',
          for: c.name,
          text: 'Stop the ' + who + ' from ' + ING[s.action || 'create'] + ' ' + t.label.toLowerCase(),
        });
      else if (s.do === 'hidden' && t.owner && accOf(def, s.role, t.name).list === 'all')
        out.push({
          by: 'backend',
          for: c.name,
          text: 'Let the ' + who + ' see their own ' + t.label.toLowerCase(),
        });
      else if (s.do === 'see' && /^403/.test(f.actual.replace(/^step \d+: /, '')))
        out.push({
          by: 'backend',
          for: c.name,
          text: 'Let the ' + who + ' see ' + t.label.toLowerCase(),
        });
      else if (s.do === 'create' && /403/.test(f.actual))
        out.push({
          by: 'backend',
          for: c.name,
          text: 'Let the ' + who + ' create ' + t.label.toLowerCase(),
        });
    });
  return out.filter((x, i, a) => a.findIndex((y) => y.text === x.text) === i);
}
