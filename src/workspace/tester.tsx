export function keepFix(
  app: BackedApp,
  text: string,
  ctx: Parameters<typeof applyChangeSync>[2],
): { ok: true; items: string[]; station: string } | { ok: false; why: string; station?: undefined } {
  // one plain change request, applied for real. applyChangeSync works inside a savepoint and puts everything back if any check fails.
  let plan: ParsedChange;
  try {
    plan = parseChange(app, text);
  } catch {
    plan = {};
  }
  if (!plan.ops || !plan.ops.length)
    return {
      ok: false,
      why: 'It could not be read as a change.',
    };
  const p = planOps(app, plan.ops);
  if (!p.steps.length)
    return {
      ok: false,
      why: p.errors[0] || 'It cannot be applied to this app.',
    };
  if (p.steps.some((s) => s.destructive))
    return {
      ok: false,
      why: 'It deletes data, so it waits for your approval in chat.',
    };
  let res;
  const n0 = app.def.migrations.length;
  try {
    res = applyChangeSync(app, p.steps, ctx);
  } catch (e) {
    return {
      ok: false,
      why: errText(e),
    };
  }
  if (res.failed)
    return {
      ok: false,
      why: stName(res.failed) + ' would fail: ' + (res.per[res.failed]?.issues[0] || 'a check'),
    };
  STATIONS.forEach((st, i) => {
    const r = res.per[st.id],
      L = app.line[st.id];
    if (i >= res.first && r) {
      L.checks = r.checks;
      L.facts = r.facts;
    }
  });
  keepChange(app, p.steps, n0, text);
  app.updated = Date.now();
  return {
    ok: true,
    items: p.steps.map((s) => s.text),
    station: STATIONS[res.first].id,
  };
}
/**
 * The Tester's part of a build, as the four steps the workflow graph calls: write the cases, run every test, send the
 * failures back for repair, and record the result. The graph decides how often `run` and `repair` happen (at most
 * `testerMax` runs, in src/platform/orchestrator/compile.ts) and emits the `tests` step events itself.
 */
export function testerSteps(app: BackedApp, run: Run) {
  const live = app.mode === 'live' && liveModelOn(),
    ctx = ctxOf(app, run, 'tester'),
    rec = app.tpl ? REC[app.tpl] : undefined;
  // write() sets Q before the graph calls the other steps
  let Q!: QaState;
  let fails: FailingTest[] = [];
  async function write() {
    Q = app.qa = {
      status: 'working',
      by: '',
      rounds: [],
      t0: Date.now(),
      t1: null,
      dropped: [],
    };
    if (U.follow[app.id] !== false) U.sel[app.id] = 'qa';
    commit();
    const s1 = stepStart(run, 'tests', 'tester', 'Write test cases', live ? 'model' : 'tool');
    let raw = null;
    say(
      app,
      'tester',
      live
        ? 'Reading the brief and writing test cases for its rules and user stories.'
        : rec && rec.tester
          ? 'Writing test cases from the brief: one for every rule, and one refusal for every role that has limits.'
          : 'Writing test cases from the rules of the brief and the access rules.',
    );
    if (live) {
      try {
        raw = await callModel(app, run, 'tester', testerPrompt(app), 1);
        Q.by = 'model';
      } catch (e) {
        if (e instanceof Stopped || (e as { fatal?: boolean }).fatal) throw e;
        raw = null;
      }
    } else {
      await pace(app, 900);
      if (rec && rec.tester) {
        raw = rec.tester();
        Q.by = 'saved';
        run.replayed++;
      }
    }
    const sorted = unplayable(normCases(raw, app.def), app.def);
    let cases = sorted.keep;
    sorted.drop.forEach((d) => Q.dropped.push(d));
    if (cases.length < 2) {
      cases = normCases(
        {
          cases: suggestCases(app),
        },
        app.def,
      );
      Q.by = Q.by === 'model' ? "rules, because the model's cases could not be used" : 'rules';
    }
    app.def.cases = fillWorkflowSteps(cases, app.def);
    app.rev++;
    stepEnd(s1, true);
    toolCall(
      ctx,
      'write_test_cases',
      {
        cases: cases.length,
      },
      () => ({
        written: cases.map((c) => c.name),
      }),
      'backend',
    );
    emit('STATE_DELTA', {
      app: app.id,
      delta: [
        {
          op: 'add',
          path: '/cases',
          value: cases.length + ' test cases',
        },
      ],
    });
    commit();
  }
  async function runRound({ round: n }: { round: number }) {
    Q.status = 'checking';
    commit();
    const s2 = stepStart(run, 'tests', 'orchestrator', n === 1 ? 'Run every test' : 'Run every test again', 'check');
    await pace(app, 800);
    const ts = runTestsSync(app);
    fails = failingTests(app);
    const R = {
      n,
      total: ts ? ts.total : 0,
      failed: ts ? ts.failed : 0,
      fails: fails.slice(0, 8).map((f) => ({
        name: f.name,
        suite: f.suiteName,
        actual: f.actual,
      })),
      fixes: [],
    };
    Q.rounds.push(R);
    stepEnd(s2, !R.failed);
    commit();
    return { total: R.total, failed: R.failed };
  }
  async function repair({ round: n }: { round: number }) {
    const R = Q.rounds[Q.rounds.length - 1];
    Q.status = 'sentback';
    run.retries++;
    say(
      app,
      'tester',
      R.failed +
        ' of ' +
        R.total +
        ' tests ' +
        (R.failed === 1 ? 'fails' : 'fail') +
        ': ' +
        fails
          .slice(0, 2)
          .map((f) => '“' + f.name + '” (' + f.actual + ')')
          .join('; ') +
        '. I am sending ' +
        (R.failed === 1 ? 'it' : 'them') +
        ' back for repair.',
      {
        type: 'error',
        issues: fails.slice(0, 3).map((f) => f.name + ': ' + f.actual),
      },
    );
    const s3 = stepStart(run, 'tests', 'backend', 'Repair', live ? 'model' : 'tool');
    let fixes: Repair[] = [],
      wrong: { id: string; why: string }[] = [];
    if (live) {
      try {
        const tried = Q.rounds.flatMap((x) => x.fixes.filter((f) => f.ok).map((f) => f.text));
        const o = await callModel(app, run, 'backend', repairPrompt(app, fails, tried), n);
        fixes = arr(o.fixes)
          .map((x) => ({
            by: 'backend',
            for: str(x && x.for),
            text: str(x && x.change),
          }))
          .filter((x) => x.text)
          .slice(0, 5);
        wrong = arr(o.wrong)
          .map((x) => ({
            id: snake(x && x.case),
            why: str(x && x.why),
          }))
          .filter((x) => (app.def.cases || []).some((c) => c.id === x.id));
      } catch (e) {
        if (e instanceof Stopped || (e as { fatal?: boolean }).fatal) throw e;
      }
    }
    if (!fixes.length && !wrong.length) {
      await pace(app, 700);
      fixes = ruleRepairs(app, fails);
    }
    if (wrong.length) {
      app.def.cases = (app.def.cases || []).filter((c) => !wrong.some((w) => w.id === c.id));
      app.rev++;
      wrong.forEach((w) => Q.dropped.push(w));
    }
    fixes.forEach((f) => {
      const r = keepFix(app, f.text, ctxOf(app, run, f.by));
      R.fixes.push({
        by: f.by,
        text: f.text,
        for: f.for,
        ok: r.ok,
        why: r.ok ? r.items.join('; ') : r.why,
        station: r.station || 'backend',
      });
    });
    stepEnd(s3, R.fixes.some((f) => f.ok) || wrong.length > 0);
    const okN = R.fixes.filter((f) => f.ok).length;
    if (!okN && !wrong.length) {
      say(
        app,
        'backend',
        'I could not find a repair that passes every check, so the failing ' +
          (R.failed === 1 ? 'test stays' : 'tests stay') +
          ' for you to decide.',
      );
      return { progress: false };
    }
    say(
      app,
      'backend',
      (okN
        ? 'Repaired: ' +
          R.fixes
            .filter((f) => f.ok)
            .map((f) => f.why)
            .join('; ') +
          '. '
        : '') +
        (wrong.length
          ? wrong.length +
            ' test case' +
            (wrong.length === 1 ? ' was' : 's were') +
            ' withdrawn because ' +
            (wrong.length === 1 ? 'it' : 'they') +
            ' did not match the brief. '
          : '') +
        'Each repair went through the same checks as a change you ask for.',
      {
        type: 'changed',
        items: R.fixes.filter((f) => f.ok).map((f) => f.why),
        reran: ['Tests'],
        skipped: [],
      },
    );
    commit();
    await pace(app, 500);
    return { progress: true };
  }
  async function done() {
    const last = Q.rounds[Q.rounds.length - 1];
    Q.status = last.failed ? 'failed' : 'ok';
    Q.t1 = Date.now();
    const repaired = Q.rounds.reduce((k, r) => k + r.fixes.filter((f) => f.ok).length, 0);
    say(
      app,
      'tester',
      last.failed
        ? last.failed +
            ' of ' +
            last.total +
            ' tests still fail. The app works, but a version can only be released when every test passes. Ask for a change in chat, or open the tests.'
        : 'All ' +
            last.total +
            ' tests pass' +
            (repaired ? ' after ' + repaired + (repaired === 1 ? ' repair' : ' repairs') : '') +
            ': ' +
            (app.def.cases || []).length +
            ' cases I wrote and ' +
            (last.total - (app.def.cases || []).length) +
            ' generated from the definitions.',
      {
        type: 'tests',
        total: last.total,
        passed: last.total - last.failed,
        failed: last.failed,
        suites: suiteOf(app).map((s) => ({
          name: s.name,
          n: s.tests.length,
        })),
      },
    );
    commit();
  }
  return { write, run: runRound, repair, done };
}
